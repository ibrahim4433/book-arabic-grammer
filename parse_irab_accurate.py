# The auditor requires strict mapping: "إعراب" must map to TEMPLATE_C_IRAB or TEMPLATE_C_IRAB_ROW.
# We CANNOT arbitrarily split the text into targets and definitions. We must parse it where it logically makes sense.
# How do we parse it logically?
# We can look for colons (:) which usually separate the word from its parsing.
# The colons are somewhat random due to bad OCR but we must use them since they are the only separators.

def parse_irab(text):
    # Regex to find all text followed by colon.
    # To not drop any text, we find colons, take the word before it as the TARGET, and the text after it (until the next word-before-colon) as the ANALYSIS.

    parts = re.split(r'(:)', text)
    if len(parts) == 1:
        return [("", text.strip())]

    blocks = []

    first_part = parts[0].strip()
    first_words = first_part.split()

    if len(first_words) > 2:
        prefix = " ".join(first_words[:-2])
        word = " ".join(first_words[-2:])
    else:
        prefix = ""
        word = " ".join(first_words)

    if prefix:
        blocks.append(("", prefix))

    current_word = word + parts[1]
    current_details = ""

    for i in range(2, len(parts) - 1, 2):
        chunk = parts[i]

        words = chunk.split()
        if len(words) > 2:
            details = " ".join(words[:-2])
            next_word = " ".join(words[-2:])
        else:
            details = ""
            next_word = " ".join(words)

        current_details += details
        blocks.append((current_word.strip(), current_details.strip()))

        current_word = next_word + parts[i+1]
        current_details = ""

    blocks.append((current_word.strip(), parts[-1].strip()))

    return blocks

