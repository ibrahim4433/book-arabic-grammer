def add_poem(right, left):
    b = poem_tmpl.replace("[POEM_TITLE]", "")
    b = b.replace("[RIGHT_HEMISTICH]", right)
    b = b.replace("[LEFT_HEMISTICH]", left)
    return b

def add_block(content):
    b = block_tmpl.replace("[BLOCK_TITLE]", "")
    b = b.replace("[CONTENT]", content)
    return b

def add_irab(items):
    # Items is a list of tuples (word, details)
    # Group them by 2s for irab_row
    html = ""
    for i in range(0, len(items), 2):
        if i + 1 < len(items):
            b = irab_row_tmpl.replace("[WORD_1]", items[i][0]).replace("[DETAILS_1]", items[i][1])
            b = b.replace("[WORD_2]", items[i+1][0]).replace("[DETAILS_2]", items[i+1][1])
            html += b
        else:
            # Only 1 item left
            b = irab_row_tmpl.replace("[WORD_1]", items[i][0]).replace("[DETAILS_1]", items[i][1])
            b = b.replace('<div class="irab-box flex-1" id="[UNIQUE_ID_2]">\n        <div class="irab-word">[WORD_2]</div>\n        <div class="irab-details">[DETAILS_2]</div>\n    </div>', "")
            html += b
    return html


