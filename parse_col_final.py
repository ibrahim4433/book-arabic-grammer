col1 = []
col2 = []

for line in text.split('\n'):
    line = line.strip()
    idx = len(line) // 2
    space_idx = line.rfind(" ", 0, idx + 10)
    if space_idx != -1:
         left = line[space_idx:].strip()
         right = line[:space_idx].strip()
    else:
         left = line
         right = ""
    col1.append(right)
    col2.append(left)

